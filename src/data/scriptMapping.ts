export function getScriptFromMapping(): Script {
  const allSceneCodes = new Set<string>();
  Object.values(characterMap).forEach((scenes) => scenes.forEach((s) => allSceneCodes.add(s)));
  Object.values(sceneMap).forEach((scenes) => scenes.forEach((s) => allSceneCodes.add(s)));
  Object.values(lightingMap).forEach((scenes) => scenes.forEach((s) => allSceneCodes.add(s)));
  Object.values(propMap).forEach((scenes) => scenes.forEach((s) => allSceneCodes.add(s)));

  const sortedCodes = Array.from(allSceneCodes).sort((a, b) => {
    const na = parseInt(a.slice(2));
    const nb = parseInt(b.slice(2));
    return na - nb;
  });

  const scenes: Scene[] = sortedCodes.map((code, idx) => {
    const meta = sceneHeaders[code] || {
      header: `${idx + 1} 未命名场景 ${code}`,
      summary: '场景信息待补充',
    };

    const chars = Object.entries(characterMap)
      .filter(([, sc]) => sc.includes(code))
      .map(([name]) => name);

    const props = Object.entries(propMap)
      .filter(([, sc]) => sc.includes(code))
      .map(([name]) => name);

    const scenes_assoc = Object.entries(sceneMap)
      .filter(([, sc]) => sc.includes(code))
      .map(([name]) => name);

    const lights = Object.entries(lightingMap)
      .filter(([, sc]) => sc.includes(code))
      .map(([name]) => name);

    return {
      id: code,
      sceneNumber: `SC${String(idx + 1).padStart(3, '0')}`,
      sceneCode: code,
      header: meta.header,
      summary: meta.summary,
      lines: [],
      associatedCharacters: chars,
      associatedProps: props,
      associatedScenes: scenes_assoc,
      associatedLighting: lights,
    };
  });

  const totalCharacters = Object.keys(characterMap);
  const totalProps = Object.keys(propMap);
  const totalScenes = Object.keys(sceneMap);
  const totalLighting = Object.keys(lightingMap);

  return {
    id: 'script_the_hakim',
    title: 'The Hakim（哈基姆）',
    synopsis: '改编自真实历史事件，讲述巴林从珍珠小国发展成现代国家的壮阔史诗。时间跨度：1861年 - 1932年。',
    scenes,
    totalCharacters,
    totalProps,
    totalScenes,
    totalLighting,
  };
}
